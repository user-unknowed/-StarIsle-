def build_corpus():
    """从 knowledge_base.json + PRD 句式语料构建中文语料。"""
    lines = []

    # 1) 抽取知识库中文文本
    with open(KB_PATH, "r", encoding="utf-8") as f:
        kb = json.load(f)

    kb_segment_count = 0
    for entry in kb:
        # content 字段按句号/分号切分为多句，增加上下文多样性
        content = entry.get("content", "")
        for clause in content.replace("；", "。").split("。"):
            clause = clause.strip()
            if len(clause) > 8:
                lines.append(clause)
                kb_segment_count += 1
        # tags / techniques / applicable_issues 拼成语义句
        tags = entry.get("tags", [])
        if tags:
            lines.append("、".join(tags) + "是" + entry.get("category", "心理治疗") + "的核心技术标签。")
            kb_segment_count += 1
        techniques = entry.get("techniques", [])
        if techniques:
            lines.append(entry.get("title", "心理治疗") + "的关键技术包括：" + "、".join(techniques) + "。")
            kb_segment_count += 1
        issues = entry.get("applicable_issues", [])
        if issues:
            lines.append("该方法适用于" + "、".join(issues) + "等心理问题。")
            kb_segment_count += 1
        # 标题本身作为一句
        title = entry.get("title", "").strip()
        if title:
            lines.append(title + "是" + entry.get("category", "心理治疗") + "领域的重要方法。")
            kb_segment_count += 1

    # 2) 追加 PRD 对齐句式语料（重复 3 轮以增加词频，满足 min_count）
    for _ in range(3):
        for s in PRD_ALIGNED_SENTENCES:
            lines.append(s)

    out_text = "\n".join(lines)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(out_text)

    print(f"[build_chinese_corpus] knowledge_base 段落数: {kb_segment_count}")
    print(f"[build_chinese_corpus] PRD 句式数: {len(PRD_ALIGNED_SENTENCES)} (x3 轮)")
    print(f"[build_chinese_corpus] 总行数: {len(lines)}")
    print(f"[build_chinese_corpus] 总字符数: {len(out_text)}")
    print(f"[build_chinese_corpus] 输出: {OUT_PATH}")

    # 统计核心词覆盖
    core_words = ["抑郁", "焦虑", "情绪", "心理健康", "治疗", "症状",
                  "心情", "开心", "平静", "低落", "难过", "放松",
                  "冥想", "压力", "自伤", "自杀", "青少年", "学生",
                  "教师", "家长", "认知行为疗法", "CBT", "风险",
                  "危机", "罗夏", "投射"]
    print("[build_chinese_corpus] 核心词覆盖检查:")
    for w in core_words:
        cnt = out_text.count(w)
        print(f"  {w}: {cnt} 次")


if __name__ == "__main__":
    build_corpus()
